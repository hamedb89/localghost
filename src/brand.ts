export function renderLocalghostBanner() {
  return [
    "   .-.",
    "  (o o)   LOCALGHOST",
    "  | O \\   friendly local domains",
    "   \\   \\",
    "    `~~~'"
  ].join("\n");
}

export function renderCompactLocalghostBanner() {
  return [
    "  .--.",
    " ( oo )  localghost",
    "  \\__/   friendly local domains"
  ].join("\n");
}
